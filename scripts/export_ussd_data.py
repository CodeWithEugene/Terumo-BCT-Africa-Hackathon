"""Write the small data file the Vercel USSD and SMS functions read.

The hosted functions in frontend/api cannot run the forecast engine, so this script runs it once
and saves the answers for the default date as plain JSON-in-JavaScript. Run it again whenever the
data, the model or the default date changes:

    python scripts/export_ussd_data.py

Output: frontend/api/_data/ussd-data.js  (no phone numbers, no keys, nothing personal).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend import config  # noqa: E402
from backend.api import service  # noqa: E402
from backend.api.sms import alert_text  # noqa: E402
from backend.engine import words  # noqa: E402
from backend.engine.brief import summary_sentence  # noqa: E402
from backend.engine.projection import morning_list  # noqa: E402
from backend.engine.world import get_world  # noqa: E402


def main() -> None:
    world = get_world()
    snap = service.snapshot(None)
    products = config.load_settings("blood")["products"]
    order = {g: n for n, g in enumerate(config.load_settings("blood")["blood_groups"])}
    hospitals = {}
    for facility, row in world.facility[world.facility["kind"] == "hospital"].iterrows():
        by_product = {}
        for component in products:
            if (facility, component) not in snap.held:
                continue
            views = sorted(morning_list(snap, facility, component), key=lambda v: order[v["blood_group"]])
            groups = []
            for v in views:
                if not v["held"]:
                    continue
                s = v.get("suggestion")
                groups.append({
                    "group": v["blood_group_label"], "status": v["status"], "statusLabel": v["status_label"],
                    "cover": v["cover_days"], "capped": bool(v.get("cover_capped")), "shelf": v["units_on_shelf"],
                    "stockout": words.day(v["stockout_date"]) if v.get("stockout_date") else None,
                    "delivery": v["next_delivery"]["label"] if v.get("next_delivery") else None,
                    "quantity": s["quantity"] if s else 0, "title": s["title"] if s else None,
                    "sum": s["sum_text"] if s else None,
                })
            by_product[component] = {"label": products[component]["label"], "groups": groups}
        rbc = morning_list(snap, facility, "RBC")
        hospitals[facility] = {
            "name": row["name"], "centre": row["supply_centre_id"],
            "summary": summary_sentence(rbc) if any(v["held"] for v in rbc) else None,
            "alert": alert_text(facility), "products": by_product,
        }
    access = config.load_settings("access")
    users = {u["username"]: {"role": u["role"], "facility": u["facility_id"]} for u in access["demo_users"]}
    data = {"asOf": str(snap.as_of.date()), "day": words.day(snap.as_of), "hospitals": hospitals, "users": users}
    out = ROOT / "frontend" / "api" / "_data" / "ussd-data.js"
    out.write_text("// Generated by scripts/export_ussd_data.py. Do not edit by hand.\nexport default "
                   + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"Wrote {out.relative_to(ROOT)} for {data['asOf']}: {len(hospitals)} hospitals.")


if __name__ == "__main__":
    main()
